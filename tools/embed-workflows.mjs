#!/usr/bin/env node
// Regenerates js/workflows.js from build-repo-template/.
// Single source of truth: edit the real files, run `node tools/embed-workflows.mjs`.
//
// Paths are relative to the repository root, which is also the GitHub Pages
// root — index.html, js/ and styles/ all sit there.
//
//   requires: node >= 18, no packages.

import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const src = join(root, 'build-repo-template');
const out = join(root, 'js/workflows.js');

const FILES = [
  '.github/workflows/build.yml',
  '.github/workflows/cleanup.yml',
  'scripts/targets.mjs',
  'scripts/detect.mjs',
  'scripts/tenc.mjs',
  'scripts/unseal.mjs',
  'scripts/relay.mjs',
  'scripts/package.mjs',
  'scripts/compile.sh',
  'scripts/sweep.mjs',
  'README.md',
  '.gitignore',
];

const parts = [];
const hash = createHash('sha256');

for (const rel of FILES) {
  const text = readFileSync(join(src, rel), 'utf8');
  hash.update(rel).update('\0').update(text).update('\0');
  const escaped = text.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${');
  parts.push(`  ${JSON.stringify(rel)}: \`${escaped}\`,`);
}

const revision = hash.digest('hex').slice(0, 12);

writeFileSync(out, `// GENERATED by tools/embed-workflows.mjs — do not edit.
// Source: build-repo-template/
//
// The frontend writes these into each user's crucible during provisioning, and
// compares them on every visit so an outdated crucible can be re-lined with one
// click.

export const TEMPLATE_REVISION = ${JSON.stringify(revision)};

export const TEMPLATE = {
${parts.join('\n')}
};

export const TEMPLATE_PATHS = Object.keys(TEMPLATE);
`);

console.log(`embedded ${FILES.length} files into js/workflows.js, revision ${revision}`);
